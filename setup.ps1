# One-click setup: venv, dependencies, and AI_MODEL / AI_BASE_URL / AI_API_KEY.
$ErrorActionPreference = "Stop"
$Root = Split-Path -Parent $MyInvocation.MyCommand.Path
Set-Location $Root

function Read-Default([string]$Prompt, [string]$Default) {
	if ($Default) {
		$shown = $Default
		if ($Prompt -match "KEY") {
			if ($Default.Length -le 8) { $shown = "********" }
			else { $shown = $Default.Substring(0, 6) + "..." + $Default.Substring($Default.Length - 4) }
		}
		$value = Read-Host "$Prompt [$shown]"
		if ([string]::IsNullOrWhiteSpace($value)) { return $Default }
		return $value
	}
	return Read-Host $Prompt
}

function Get-EnvValue([string]$Path, [string]$Key) {
	if (-not (Test-Path $Path)) { return "" }
	foreach ($line in Get-Content -Path $Path -Encoding UTF8) {
		$trim = $line.Trim()
		if ($trim.StartsWith("#") -or -not $trim.Contains("=")) { continue }
		$parts = $trim.Split("=", 2)
		if ($parts[0].Trim() -eq $Key) { return $parts[1].Trim().Trim("'").Trim('"') }
	}
	return ""
}

Write-Host "=== SecPaper-DeepScan setup ===" -ForegroundColor Cyan

$python = Get-Command python -ErrorAction SilentlyContinue
if (-not $python) {
	throw "Python not found. Install Python 3.10+ and retry."
}

$venvPython = Join-Path $Root ".venv\Scripts\python.exe"
if (-not (Test-Path $venvPython)) {
	Write-Host "Creating virtualenv .venv ..."
	python -m venv .venv
}
Write-Host "Installing requirements ..."
& $venvPython -m pip install --upgrade pip
& $venvPython -m pip install -r (Join-Path $Root "requirements.txt")

$envPath = Join-Path $Root ".env"

$currentModel = Get-EnvValue $envPath "AI_MODEL"
if (-not $currentModel) { $currentModel = "qwen3.7-plus" }
$currentUrl = Get-EnvValue $envPath "AI_BASE_URL"
if (-not $currentUrl) { $currentUrl = "https://dashscope.aliyuncs.com/compatible-mode/v1" }
$currentKey = Get-EnvValue $envPath "AI_API_KEY"

Write-Host ""
Write-Host "Configure analyzer AI settings (Enter keeps the current/default value)."
$model = Read-Default "AI_MODEL" $currentModel
$baseUrl = Read-Default "AI_BASE_URL" $currentUrl
$apiKey = Read-Default "AI_API_KEY" $currentKey
if ([string]::IsNullOrWhiteSpace($apiKey)) {
	throw "AI_API_KEY is required."
}

@(
	"# Generated by setup.ps1"
	"AI_MODEL=$model"
	"AI_BASE_URL=$baseUrl"
	"AI_API_KEY=$apiKey"
) | Set-Content -Path $envPath -Encoding UTF8

Write-Host ""
Write-Host "Wrote $envPath" -ForegroundColor Green
Write-Host "Activate venv:  .\.venv\Scripts\Activate.ps1"
Write-Host "Then run:       python src/fetcher_add_summary.py --help"
Write-Host "                python src/analyzer_no_summary.py --help"
